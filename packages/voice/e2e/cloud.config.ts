// LiveKit Cloud runtime check against a DEPLOYED Moonveil (no local server, no LiveKit started here, no secret):
//   VOICE_CLOUD_URL=https://<app-host> node scripts/env.mjs npm run e2e:cloud -w @moonveil/voice
// Budget guard: VOICE_CLOUD_CAP_MIN (participant-minutes, default 60; approved total for probes: 100).
// Traces, videos and screenshots are OFF: wire capture would store LiveKit tokens in artifacts.
import { defineConfig, devices } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const cache = path.join(root, '.cache', 'voice-cloud');
fs.mkdirSync(path.join(cache, 'home'), { recursive: true });
const url = process.env.VOICE_CLOUD_URL;
if (!url) throw new Error('VOICE_CLOUD_URL (public https URL of the deployed app) is required');

// Same speech-like fake microphone as the local suite (generated by its config; copied here if present).
const wav = path.join(cache, 'speechlike.wav');
if (!fs.existsSync(wav)) {
  const src = path.join(root, '.cache', 'voice-e2e', 'speechlike.wav');
  if (fs.existsSync(src)) fs.copyFileSync(src, wav);
  else {
    const sr = 48000, n = sr * 10, amp = 0.5;
    const buf = Buffer.alloc(44 + n * 2);
    buf.write('RIFF', 0); buf.writeUInt32LE(36 + n * 2, 4); buf.write('WAVEfmt ', 8); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
    buf.writeUInt32LE(sr, 24); buf.writeUInt32LE(sr * 2, 28); buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34); buf.write('data', 36); buf.writeUInt32LE(n * 2, 40);
    const f0s = [220, 330, 440, 550, 660, 880];
    const period = Math.round(sr * 0.38), burst = Math.round(sr * 0.2);
    for (let i = 0; i < n; i++) {
      const k = Math.floor(i / period), t = (i % period) / sr;
      let v = 0;
      if (i % period < burst) {
        const f0 = f0s[k % f0s.length]! * (1 + 0.05 * Math.sin((2 * Math.PI * i) / sr));
        const env = Math.sin((Math.PI * (i % period)) / burst);
        v = env * (Math.sin(2 * Math.PI * f0 * t) + 0.5 * Math.sin(2 * Math.PI * 2 * f0 * t) + 0.25 * Math.sin(2 * Math.PI * 3 * f0 * t)) / 1.75;
      }
      buf.writeInt16LE(Math.round(amp * 32767 * v), 44 + i * 2);
    }
    fs.writeFileSync(wav, buf);
  }
}

